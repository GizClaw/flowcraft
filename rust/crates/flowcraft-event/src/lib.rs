//! Subjects, patterns and envelopes: the routing half of `core/event`.
//!
//! An event bus is not a shape, but what travels on it is, and this crate is
//! where the port keeps the contract half of core's package:
//!
//! - [`Subject`] and [`Pattern`] -- the dot-delimited routing key and its
//!   NATS-style matcher, with core's validation sentences, because a producer
//!   and a subscriber in different processes have to agree on which events a
//!   pattern selects;
//! - [`Envelope`] -- the carrier, its well-known header names, and the JSON a
//!   cross-process bus forwards verbatim;
//! - [`time`] -- the timestamp spelling `encoding/json` gives a `time.Time`,
//!   which is the envelope's `time` field.
//!
//! The in-process bus lands as its own slice. It needs a concurrency model
//! chosen on purpose rather than a translation of Go's mutexes and wait groups,
//! and that model is the decision the runtime slice has to make first.
//!
//! # What a caller can tell apart from core
//!
//! Three things, all documented where they happen: an envelope's `time` is
//! written in UTC where Go writes the local zone (same instant, same RFC 3339
//! grammar), envelope *decoding* is not here yet (it lands with the bus, which
//! is the first reader), and `NewEnvelope`'s identifier is generated by
//! [`id::next`], which reproduces `rs/xid`'s 20-character shape rather than
//! depending on the Go library.

pub mod envelope;
pub mod id;
pub mod subject;
pub mod time;

pub use envelope::Envelope;
pub use subject::{Pattern, Subject, producer_kind};
