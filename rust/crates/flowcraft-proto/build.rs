//! Generates the Rust bindings for every contract under `proto/`.
//!
//! The tree is the source of truth and it is shared with the Go SDK, so this
//! script does not enumerate files: adding `proto/flowcraft/<area>/v1/…`
//! requires no change here. Each proto package becomes one module named after
//! its area (`flowcraft.workspace.v1` → `flowcraft_proto::workspace`); a
//! non-`v1` package appends its version (`flowcraft.foo.v2` → `foo_v2`) so two
//! versions can be served side by side.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let proto_root = manifest.join("../../../proto");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR")?);

    let mut files = Vec::new();
    collect(&proto_root, &mut files)?;
    files.sort();
    if files.is_empty() {
        return Err(format!("no protos under {}", proto_root.display()).into());
    }

    let mut modules: BTreeMap<String, String> = BTreeMap::new();
    for file in &files {
        println!("cargo:rerun-if-changed={}", file.display());
        let text = std::fs::read_to_string(file)?;
        let package = text
            .lines()
            .find_map(|line| line.trim().strip_prefix("package "))
            .and_then(|rest| rest.strip_suffix(';'))
            .map(str::trim)
            .ok_or_else(|| format!("{}: no package declaration", file.display()))?;
        let parts: Vec<&str> = package.split('.').collect();
        if parts.len() != 3 || parts[0] != "flowcraft" {
            return Err(format!("{}: unsupported package {package:?}", file.display()).into());
        }
        let module = if parts[2] == "v1" {
            parts[1].to_owned()
        } else {
            format!("{}_{}", parts[1], parts[2])
        };
        if modules.insert(package.to_owned(), module).is_some() {
            return Err(format!("duplicate proto package {package:?}").into());
        }
    }
    println!("cargo:rerun-if-changed={}", proto_root.display());

    // `extern_path` marks a package as externally provided, which also stops
    // prost from generating that package's file — so the message module is
    // compiled on its own first, and everything that references it is compiled
    // with the mapping that matches this crate's flat module layout.
    let (message_files, other_files): (Vec<PathBuf>, Vec<PathBuf>) = files
        .iter()
        .cloned()
        .partition(|file| package_of(file).as_deref() == Some(MESSAGE_PACKAGE));

    tonic_prost_build::configure()
        .build_client(true)
        .build_server(true)
        .compile_protos(&message_files, std::slice::from_ref(&proto_root))?;

    tonic_prost_build::configure()
        .build_client(true)
        .build_server(true)
        .extern_path(MESSAGE_PACKAGE, "crate::message")
        .compile_protos(&other_files, std::slice::from_ref(&proto_root))?;

    let mut generated = String::from("// @generated by flowcraft-proto/build.rs — do not edit.\n");
    for (package, module) in &modules {
        generated.push_str(&format!(
            "#[allow(missing_docs)]\npub mod {module} {{\n    tonic::include_proto!(\"{package}\");\n}}\n"
        ));
    }
    std::fs::write(out_dir.join("generated.rs"), generated)?;
    Ok(())
}

/// The conversation model: a data schema referenced by craft envelopes and tool
/// results.
const MESSAGE_PACKAGE: &str = ".flowcraft.message.v1";

fn package_of(file: &Path) -> Option<String> {
    let text = std::fs::read_to_string(file).ok()?;
    text.lines()
        .find_map(|line| line.trim().strip_prefix("package "))
        .and_then(|rest| rest.strip_suffix(';'))
        .map(|name| format!(".{}", name.trim()))
}

fn collect(root: &Path, out: &mut Vec<PathBuf>) -> std::io::Result<()> {
    for entry in std::fs::read_dir(root)? {
        let entry = entry?;
        let path = entry.path();
        if path.is_dir() {
            collect(&path, out)?;
        } else if path.extension().is_some_and(|ext| ext == "proto") {
            out.push(path);
        }
    }
    Ok(())
}
